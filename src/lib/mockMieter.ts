import { JETZT } from "./mockDaten";
import type { Mieter, Mieterunterlage, Unterlagenart } from "./mieter";

function vorTagen(anzahl: number): string {
  const d = new Date(JETZT);
  d.setDate(d.getDate() - anzahl);
  return d.toISOString();
}

function vorMonaten(anzahl: number): string {
  const d = new Date(JETZT);
  d.setMonth(d.getMonth() - anzahl);
  return d.toISOString();
}

function inMonaten(anzahl: number): string {
  const d = new Date(JETZT);
  d.setMonth(d.getMonth() + anzahl);
  return d.toISOString();
}

/**
 * Kurzschreibweise für eine Akte. `gueltig` in Monaten ab heute — negativ
 * heißt abgelaufen, `null` heißt unbefristet.
 */
function akte(
  praefix: string,
  zeilen: [art: Unterlagenart, vorTagenHoch: number, gueltigMonate: number | null][],
): Mieterunterlage[] {
  return zeilen.map(([art, hoch, gueltig], i) => ({
    id: `${praefix}-u${i + 1}`,
    art,
    titel: TITEL[art],
    dateiname: `${art}_${praefix}.pdf`,
    hochgeladenAm: vorTagen(hoch),
    // Phase 2 füllt beide Wege: Supabase Storage als Wahrheit, Drive als Ablage.
    speicherpfad: null,
    driveId: null,
    gueltigBis: gueltig === null ? null : inMonaten(gueltig),
  }));
}

