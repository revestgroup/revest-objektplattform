/** Tage vor heute, als ISO-Datum. Hält die Beispiele immer aktuell. */
function vorTagen(tage: number): string {
  const d = new Date();
  d.setDate(d.getDate() - tage);
  return d.toISOString().slice(0, 10);
}

function scanZeit(tage: number, stunde: number): string {
  const d = new Date();
  d.setDate(d.getDate() - tage);
  d.setHours(stunde, 14, 0, 0);
  return d.toISOString();
}

